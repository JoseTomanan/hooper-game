"""Bake a deterministic ball target from frozen production poses and independent hand skin.

This is OFFLINE authoring. The simulation consumes the generated numeric profile,
never a bone or a capture. Palm selection sees only rest-mesh anatomy, not a ball.
"""
import argparse
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def transform(t, v, direction=False):
    return [sum(t[3 + 3 * j + i] * v[j] for j in range(3)) + (0 if direction else t[i]) for i in range(3)]


def palm(mesh, side):
    # Center of the proximal palm, distal to wrist and proximal to finger roots.
    # +Y follows the metacarpals; +Z is the palmar surface in the imported Y Bot.
    # Select an ACTUAL fully wrist-skinned surface vertex and its authored normal.
    candidates = [v for v in mesh["vertices"] if side in v["wrist_local"]
                  and len(v["influences"]) == 1
                  and v["influences"][0]["bone_name"] == "mixamorig_" + side + "Hand"
                  and v["wrist_local"][side]["normal"][2] > .8]
    chosen = min(candidates, key=lambda v: sum((v["wrist_local"][side]["position"][i]
                                               - (0, .065, .03)[i]) ** 2 for i in range(3)))
    return {"mesh": mesh["path"], **chosen}


def generate(geometry_path, trace_path, output, calibration_path):
    geometry = json.loads(geometry_path.read_text())
    mesh = next(m for m in geometry["meshes"] if m["path"].endswith("/Alpha_Surface"))
    palms = {side: palm(mesh, side) for side in ("Right", "Left")}
    rows = [json.loads(line) for line in trace_path.read_text().splitlines()]
    poses = {}
    for row in rows:
        p = row.get("pose", {})
        if p.get("move") == "jumpshot" and p.get("phase") == "Startup":
            poses.setdefault(p["frame"], p["bones"]["mixamorig_RightHand"]["body"])
    if set(range(1, 18)) - poses.keys():
        raise ValueError("Frozen production trace lacks evaluated Startup frames 1..17")
    local = palms["Right"]["wrist_local"]["Right"]
    offset = [a + .12 * n for a, n in zip(local["position"], local["normal"])]
    targets = [transform(poses[max(1, min(i, 17))], offset) for i in range(19)]
    calibration = {"schema": "normal-shot-gather-profile-v1", "rigSha256": geometry["source_sha256"],
                   "traceSha256": hashlib.sha256(trace_path.read_bytes()).hexdigest(),
                   "radius": .12, "selection": "closest pure wrist-skinned palmar vertex to anatomical (0,.065,.03), normal.z>.8; no ball inputs",
                   "palms": palms, "referenceRightWristBodyTransforms": poses, "targets": targets,
                   "assets": {p: hashlib.sha256((ROOT / p).read_bytes()).hexdigest() for p in
                              ("assets/Y Bot.fbx", "assets/locomotion.res", "assets/held.res", "scenes/Player.tscn")}}
    calibration_path.parent.mkdir(parents=True, exist_ok=True)
    calibration_path.write_text(json.dumps(calibration, indent=2) + "\n")
    lines = ["// Generated by tools/generate_shot_gather_profile.py; calibration: assets/shot_gather_calibration.json.",
             "using System;", "using Godot;", "using Hooper.Player;", "namespace Hooper.Ball;", "public static class ShotGatherProfile", "{"]
    for side in ("Right", "Left"):
        loc = palms[side]["wrist_local"][side]
        for name, key in (("Palm", "position"), ("Normal", "normal")):
            lines.append(f"    public static readonly Vector3 {side}{name} = new(" + ", ".join(f"{x:.9f}f" for x in loc[key]) + ");")
    lines += ["    private static readonly Vector3[] Targets =", "    {"]
    lines += ["        new(" + ", ".join(f"{x:.9f}f" for x in v) + ")," for v in targets]
    lines += ["    };", "    public static Vector3 Target(int frame) => Targets[Math.Clamp(frame, 0, 18)];", "}"]
    output.write_text("\n".join(lines) + "\n")
    print(f"[shot-profile] generated {len(targets)} fixed-frame targets; palms " +
          str({side: palms[side]["vertex"] for side in palms}))


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--geometry", type=Path, required=True)
    parser.add_argument("--trace", type=Path, required=True)
    parser.add_argument("--output", type=Path, default=ROOT / "scripts/Ball/ShotGatherProfile.cs")
    parser.add_argument("--calibration", type=Path, default=ROOT / "assets/shot_gather_calibration.json")
    args = parser.parse_args()
    generate(args.geometry, args.trace, args.output, args.calibration)
